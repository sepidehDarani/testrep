def sum_n (num1 , num2):
    sum=num1 + num2
    return sum
def sub_n (num1 , num2):
    sub=num1 - num2
    return sub
def mult_n (num1 , num2):
    mult=num1 * num2
    return mult
def div_n (num1 , num2):
    div=num1 / num2
    return div
s=sum_n(10,2)
su=sub_n(10,5)
m=mult_n(2,6)
d=div_n(10,2)

print(f"sum={s} and sub={su} and mult={m} and div={d}")

